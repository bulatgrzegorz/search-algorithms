#!/usr/bin/env python3
"""Turn a run.sh results folder into site/assets/bench-data.js for the GitHub Pages charts.

Usage: extract.py <results dir> <output .js>
"""
import glob
import json
import os
import re
import sys

results, output = sys.argv[1], sys.argv[2]
data = {"search": [], "typeahead": [], "build": [], "mutation": [], "footprint": []}
suites = {"SearchBenchmarks": "search", "TypeaheadBenchmarks": "typeahead", "BuildBenchmarks": "build", "MutationBenchmarks": "mutation"}
host = None

for path in sorted(glob.glob(os.path.join(results, "*", "results", "*-report-full-compressed.json"))):
    report = json.load(open(path))
    host = host or report["HostEnvironmentInfo"]
    for b in report["Benchmarks"]:
        if not b.get("Statistics"):
            continue  # failed benchmark: no result, the chart shows a dash
        params = dict(p.split("=", 1) for p in b["Parameters"].split("&"))
        data[suites[b["Type"]]].append({
            "algorithm": params["Algorithm"],
            "method": b["Method"],
            "size": params.get("Size"),
            "writes": int(params.get("WritesPerSecond", 0)),
            "mean": round(b["Statistics"]["Mean"], 3),  # ns
            "allocated": b["Memory"]["BytesAllocatedPerOperation"],
        })

# footprint logs end with one markdown table row per algorithm.
for path in sorted(glob.glob(os.path.join(results, "footprint-*.log"))):
    for line in open(path):
        cells = [c.strip().replace(",", "") for c in line.strip().strip("|").split("|")]
        if len(cells) == 9 and re.fullmatch(r"\d+", cells[1]):
            name, _, build_ms, _, _, _, heap, rss, disk = cells
            mb = 1024 * 1024
            data["footprint"].append({"algorithm": name, "buildMs": float(build_ms), "heap": float(heap) * mb, "rss": float(rss) * mb, "disk": float(disk) * mb})

assert data["search"], "no benchmark results found"
data["meta"] = {
    "machine": f"{host['ProcessorName']}, {host['PhysicalCoreCount']} cores, {host['OsVersion'].split(' [')[0]}, {host['RuntimeVersion'].split(' (')[0]}.",
    "provenance": f"BenchmarkDotNet {host['BenchmarkDotNetVersion']}, short in-process job (3 warmups, 5 iterations of 200 ms), "
                  f"{host['ProcessorName']}, {host['RuntimeVersion'].split(' (')[0]}. Good for orders of magnitude, not for small differences. "
                  "A dash means the benchmark produced no result.",
}
with open(output, "w") as f:
    f.write("// Generated by benchmarks/site-data/extract.py; do not edit by hand.\nwindow.BENCH = ")
    json.dump(data, f, separators=(",", ":"))
    f.write(";\n")
print({k: len(v) for k, v in data.items() if isinstance(v, list)})
